-- Paket dasar/VIP/Premium dengan masa aktif yang dapat ditentukan admin.
alter table public.profiles add column if not exists plan_expires_at timestamptz;
create or replace function public.jsvidey_admin_set_plan_duration(
  p_user_id uuid, p_plan text, p_duration_days integer default 0
) returns jsonb language plpgsql security definer set search_path='' as $$
declare v_plan text; v_days integer; v_expiry timestamptz;
begin
  if not public.jsvidey_is_admin() then raise exception 'Admin access required'; end if;
  v_plan := lower(trim(coalesce(p_plan,'basic')));
  v_days := greatest(0,least(coalesce(p_duration_days,0),3650));
  if v_plan not in ('basic','vip','premium') then raise exception 'Paket tidak valid'; end if;
  if v_plan='basic' then v_days:=0; v_expiry:=null;
  elsif v_days>0 then v_expiry:=now() + make_interval(days=>v_days);
  else v_expiry:=null; end if;
  update public.profiles set plan=v_plan, plan_expires_at=v_expiry where id=p_user_id;
  if not found then raise exception 'Profil member tidak ditemukan'; end if;
  return jsonb_build_object('user_id',p_user_id,'plan',v_plan,'plan_expires_at',v_expiry);
end; $$;
revoke all on function public.jsvidey_admin_set_plan_duration(uuid,text,integer) from public,anon;
grant execute on function public.jsvidey_admin_set_plan_duration(uuid,text,integer) to authenticated;

-- Hapus pesanan membership dengan pemeriksaan hak admin di database.
create or replace function public.jsvidey_admin_delete_payment_order(p_order_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare deleted_id uuid;
begin
  if not public.jsvidey_is_admin() then raise exception 'Admin access required'; end if;
  delete from public.jsvidey_payment_orders where id=p_order_id returning id into deleted_id;
  if deleted_id is null then raise exception 'Pesanan pembayaran tidak ditemukan'; end if;
  return jsonb_build_object('deleted_id',deleted_id);
end; $$;
revoke all on function public.jsvidey_admin_delete_payment_order(uuid) from public,anon;
grant execute on function public.jsvidey_admin_delete_payment_order(uuid) to authenticated;


-- Keep the database constraint aligned with the admin's access selector.
alter table public.videos drop constraint if exists videos_audience_check;
alter table public.videos add constraint videos_audience_check
  check (audience in ('public','members','vip','premium'));

-- Ensure admin media table receives audience/access from the database after every change.
create or replace function public.jsvidey_admin_dashboard()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare result jsonb;
begin
  if not public.jsvidey_is_admin() then raise exception 'Admin access required'; end if;
  select jsonb_build_object(
    'users',(select coalesce(jsonb_agg(jsonb_build_object(
      'id',u.id,'email',u.email,'username',p.username,'display_name',p.display_name,
      'created_at',u.created_at,'banned_until',u.banned_until,'plan',coalesce(p.plan,'basic'),
      'plan_expires_at',p.plan_expires_at,
      'is_admin',exists(select 1 from public.jsvidey_admins a where a.user_id=u.id)
    ) order by u.created_at desc),'[]'::jsonb) from auth.users u left join public.profiles p on p.id=u.id),
    'videos',(select coalesce(jsonb_agg(jsonb_build_object(
      'id',v.id,'title',v.title,'video_url',v.video_url,'storage_key',v.storage_key,
      'file_size_bytes',v.file_size_bytes,'status',v.status,'audience',v.audience,
      'thumbnail_url',v.thumbnail_url,'created_at',v.created_at,'user_id',v.user_id,
      'username',p.username,'email',u.email
    ) order by v.created_at desc),'[]'::jsonb) from public.videos v left join public.profiles p on p.id=v.user_id left join auth.users u on u.id=v.user_id),
    'withdrawals',(select coalesce(jsonb_agg(jsonb_build_object('id',w.id,'user_id',w.user_id,'username',p.username,'email',u.email,'amount_idr',w.amount_idr,'payout_method',w.payout_method,'payout_details',w.payout_details,'status',w.status,'admin_note',w.admin_note,'created_at',w.created_at) order by w.created_at desc),'[]'::jsonb) from public.withdraw_requests w left join public.profiles p on p.id=w.user_id left join auth.users u on u.id=w.user_id),
    'earnings',(select coalesce(jsonb_agg(jsonb_build_object('id',e.id,'user_id',e.user_id,'amount_idr',e.amount_idr,'views',e.views,'cpm_idr',e.cpm_idr,'created_at',e.created_at) order by e.created_at desc),'[]'::jsonb) from public.creator_earnings e),
    'notifications',(select coalesce(jsonb_agg(jsonb_build_object('id',n.id,'title',n.title,'body',n.body,'target_user_id',n.target_user_id,'created_at',n.created_at) order by n.created_at desc),'[]'::jsonb) from (select * from public.jsvidey_notifications order by created_at desc limit 30) n),
    'config',(select settings from public.jsvidey_platform_config where singleton=true),
    'counts',jsonb_build_object('users',(select count(*) from auth.users),'videos',(select count(*) from public.videos),'pending_withdrawals',(select count(*) from public.withdraw_requests where status='pending'),'revenue',(select coalesce(sum(amount_idr),0) from public.creator_earnings),'views',(select coalesce(sum(views),0) from public.creator_earnings),'avg_cpm',(select coalesce(avg(cpm_idr),0) from public.creator_earnings))
  ) into result;
  return result;
end; $$;
revoke all on function public.jsvidey_admin_dashboard() from public,anon;
grant execute on function public.jsvidey_admin_dashboard() to authenticated;

commit;
